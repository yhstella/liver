def render_jsonld_faq(faq):
    items = []
    for q, a in faq:
        q_esc = q.replace('"', '\\"')
        a_plain = re.sub(r'<[^>]+>', '', a).replace('"', '\\"').strip()
        items.append('{"@type":"Question","name":"' + q_esc + '","acceptedAnswer":{"@type":"Answer","text":"' + a_plain + '"}}')
    return '{"@type":"FAQPage","mainEntity":[' + ','.join(items) + ']}'

def patch_html(slug, faq):
    p = ROOT / slug / "index.html"
    if not p.exists():
        print(f"  SKIP missing: {slug}")
        return
    text = p.read_text(encoding="utf-8")
    orig = text

    # Update JSON-LD FAQPage
    new_jsonld = render_jsonld_faq(faq)
    text = re.sub(
        r'\{"@type":"FAQPage","mainEntity":\[.*?\]\}',
        lambda m: new_jsonld,
        text, count=1, flags=re.S
    )

    # Update HTML body FAQ section
    new_html = '<section class="faq" id="faq">\n<h2>자주 묻는 질문</h2>\n'
    for q, a in faq:
        new_html += f'<details><summary>{q}</summary>{a}</details>\n'
    new_html += '</section>'
    text = re.sub(
        r'<section class="faq" id="faq">.*?</section>',
        lambda m: new_html,
        text, count=1, flags=re.S
    )

    if text != orig:
        p.write_text(text, encoding="utf-8")
        print(f"  patched: {slug}")
    else:
        print(f"  no change (FAQ section not found): {slug}")

for slug, faq in EXPANDED_FAQ.items():
    if not faq:
        continue  # already handled elsewhere
    patch_html(slug, faq)

print("\nDone.")
