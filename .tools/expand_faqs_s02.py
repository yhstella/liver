def render_jsonld_faq(faq):
    items = []
    for q, a in faq:
        q_esc = q.replace('"', '\\"')
        a_plain = re.sub(r'<[^>]+>', '', a).replace('"', '\\"').strip()
        items.append(f'{{"@type":"Question","name":"{q_esc}","acceptedAnswer":{{"@type":"Answer","text":"{a_plain}"}}}}')
    return '{"@type":"FAQPage","mainEntity":[' + ','.join(items) + ']}'

def render_html_faq(faq):
    out = ['<section class="faq" id="faq">', '<h2>자주 묻는 질문</h2>']
    for q, a in faq:
        out.append(f'<details><summary>{q}</summary><p>{re.sub(chr(60)+chr(47)+"?p>", "", a)}</p></details>'.replace('<details><summary>'+q+'</summary><p><p>', '<details><summary>'+q+'</summary><p>'))
    out.append('</section>')
    return "\n".join(out)

