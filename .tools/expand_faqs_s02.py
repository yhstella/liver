hand_path = ROOT / "간경변-대상성-비대상성" / "index.html"
if hand_path.exists():
    text = hand_path.read_text(encoding="utf-8")
    faq = EXPANDED_FAQ["간경변-대상성-비대상성"]

    # Update JSON-LD FAQPage - find existing
    # Pattern: {"@type":"FAQPage","mainEntity":[...]}
    new_jsonld = render_jsonld_faq(faq)
    text = re.sub(
        r'\{"@type":"FAQPage","mainEntity":\[.*?\]\}',
        new_jsonld.replace('\\', '\\\\'),
        text, count=1, flags=re.S
    )

    # Update HTML body FAQ section
    # Find <section class="faq" id="faq">...</section> and replace
    new_html_faq = '<section class="faq" id="faq">\n<h2>자주 묻는 질문</h2>\n'
    for q, a in faq:
        new_html_faq += f'<details><summary>{q}</summary>{a}</details>\n'
    new_html_faq += '</section>'
    text = re.sub(
        r'<section class="faq" id="faq">.*?</section>',
        new_html_faq.replace('\\', '\\\\'),
        text, count=1, flags=re.S
    )

    hand_path.write_text(text, encoding="utf-8")
    print(f"  patched hand-written: 간경변-대상성-비대상성/index.html")

print("\nDone. Now run: python .tools/build_articles.py")
