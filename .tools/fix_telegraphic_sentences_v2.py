def main():
    fixed = 0
    missing = []
    for slug, old, new in REPLACEMENTS:
        f = ROOT / slug / 'index.html'
        if not f.exists():
            missing.append(slug)
            continue
        text = f.read_text(encoding='utf-8')
        if old in text:
            f.write_text(text.replace(old, new, 1), encoding='utf-8')
            fixed += 1
        else:
            missing.append(f'{slug} (pattern not found)')
    print(f'Fixed: {fixed}/{len(REPLACEMENTS)}')
    if missing:
        print('Misses:')
        for m in missing:
            print(f'  {m}')


if __name__ == '__main__':
    main()
