FAQ_BLOCK_RE = re.compile(
    r'(<section class="faq-block">)(.*?)(</section>)',
    re.DOTALL,
)


def normalize_slug(slug: str) -> Path:
    if "/" in slug:
        return ROOT / slug / "index.html"
    return ROOT / slug / "index.html"


def main():
    by_slug: dict[str, list[tuple[str, str]]] = {}
    for slug, old, new in REWRITES:
        by_slug.setdefault(slug, []).append((old, new))

    total_pages = 0
    total_rewrites = 0
    not_found = []

    for slug, pairs in by_slug.items():
        path = normalize_slug(slug)
        if not path.exists():
            print(f"  [MISS] {slug} — file not found")
            continue
        text = path.read_text(encoding="utf-8")
        m = FAQ_BLOCK_RE.search(text)
        if not m:
            print(f"  [MISS] {slug} — no FAQ block")
            continue

        faq = m.group(2)
        page_count = 0
        for old, new in pairs:
            if old in faq:
                faq = faq.replace(old, new)
                page_count += 1
            else:
                not_found.append((slug, old[:60]))

        if page_count > 0:
            new_text = text[:m.start(2)] + faq + text[m.end(2):]
            path.write_text(new_text, encoding="utf-8")
            total_pages += 1
            total_rewrites += page_count
            print(f"  [{page_count:2d}] {slug}")

    print()
    print(f"확장 완료: {total_pages} 페이지, 총 {total_rewrites} 건 rewrite")
    if not_found:
        print(f"\n매칭 실패 (검수 필요): {len(not_found)}건")
        for slug, frag in not_found[:10]:
            print(f"  {slug}: {frag}...")


if __name__ == "__main__":
    main()
