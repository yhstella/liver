def detail_pages():
    for p in ROOT.iterdir():
        if p.is_dir() and p.name not in EXCLUDE and not p.name.startswith('.'):
            idx = p / 'index.html'
            if idx.exists():
                yield idx


def main():
    pages = 0
    by_rule = {}
    for f in detail_pages():
        text = f.read_text(encoding='utf-8')
        new = text
        for old, repl in LITERAL:
            if old in new:
                n = new.count(old)
                new = new.replace(old, repl)
                by_rule[old] = by_rule.get(old, 0) + n
        if new != text:
            f.write_text(new, encoding='utf-8')
            pages += 1
    print(f'Pages changed: {pages}\n')
    for rule, count in sorted(by_rule.items(), key=lambda x: -x[1]):
        short = rule.replace('\n', '\\n')[:60]
        print(f'  {count:3d} × "{short}{"…" if len(rule)>60 else ""}"')


if __name__ == '__main__':
    main()
